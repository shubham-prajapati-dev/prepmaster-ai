
import { GoogleGenAI } from "@google/genai";

const ai = new GoogleGenAI({
  apiKey: process.env.GEMINI_API_KEY,
});

const questionSchema = {
  type: "OBJECT",
  properties: {
    questions: {
      type: "ARRAY",
      items: {
        type: "OBJECT",
        properties: {
          prompt: { type: "STRING" },
          options: {
            type: "ARRAY",
            items: { type: "STRING" },
          },
          correctAnswerIndex: { type: "INTEGER" },
          explanation: { type: "STRING" },
          topic: { type: "STRING" },
        },
        required: [
          "prompt",
          "options",
          "correctAnswerIndex",
          "explanation",
          "topic",
        ],
      },
    },
  },
  required: ["questions"],
};

export async function generateVocabularyQuestions(
  difficulty = "easy"
) {
  if (!process.env.GEMINI_API_KEY) {
    throw new Error("GEMINI_API_KEY is missing");
  }

  const response = await ai.models.generateContent({
    model: process.env.GEMINI_MODEL || "gemini-flash-latest",

    contents: `
      You are an expert placement examination question setter.

      Generate exactly 10 original English vocabulary MCQs.

      Difficulty: ${difficulty}

      Include a mixture of:
      1. Synonyms
      2. Antonyms
      3. Idioms
      4. Fill in the blanks
      5. Correct word usage
      6. Error identification

      Rules:
      - Exactly four options per question.
      - Exactly one correct answer.
      - correctAnswerIndex must be between 0 and 3.
      - No duplicate options.
      - Provide a clear explanation.
      - Questions must be accurate and unambiguous.

      Return only structured JSON.
    `,

    config: {
      responseMimeType: "application/json",
      responseSchema: questionSchema,
      temperature: 0.7,
    },
  });

  if (!response.text) {
    throw new Error("Gemini returned an empty response");
  }

  const result = JSON.parse(response.text);

  if (
    !Array.isArray(result.questions) ||
    result.questions.length !== 10
  ) {
    throw new Error("Gemini must generate exactly 10 questions");
  }

  for (const q of result.questions) {
    if (
      typeof q.prompt !== "string" ||
      !Array.isArray(q.options) ||
      q.options.length !== 4 ||
      q.options.some((option) => typeof option !== "string") ||
      new Set(q.options).size !== 4 ||
      !Number.isInteger(q.correctAnswerIndex) ||
      q.correctAnswerIndex < 0 ||
      q.correctAnswerIndex > 3 ||
      typeof q.explanation !== "string" ||
      typeof q.topic !== "string"
    ) {
      throw new Error("Invalid question generated by Gemini");
    }
  }

  return result.questions;
}
